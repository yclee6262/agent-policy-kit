  const settings = existsSync(path) ? readJson(path) : {};
  const current = settings.context && settings.context.fileName;
  const values = current === undefined ? [] : (Array.isArray(current) ? current : [current]);
  const conflicts = values.filter((value) => value !== "AGENTS.md");
  if (conflicts.length && !force) {
    throw new Error(`Gemini context.fileName already includes ${conflicts.join(", ")}. Review for conflicting policy or rerun with --force.`);
  }
  settings.context = { ...(settings.context || {}), fileName: "AGENTS.md" };
