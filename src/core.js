export function setupTool(root, tool, options = {}) {
  assertAtRoot(root);
  if (tool !== "all" && !SUPPORTED_TOOLS.includes(tool)) throw new Error(`Unsupported tool: ${tool}`);
  const sync = syncProject(root, options);
  const tools = tool === "all" ? SUPPORTED_TOOLS : [tool];
  const manifest = loadManifest(root);
  const adapters = {};
  for (const item of tools) {
    let result;
    if (item === "gemini") result = setupGemini(root, options.force);
    else if (item === "claude") result = setupClaude(root, options.force);
    else result = setupDirect(root, item);
    adapters[item] = result;
    manifest.adapters = manifest.adapters || {};
    manifest.adapters[item] = { ...result, configured_at: timestamp() };
  }
  if (tools.includes("gemini")) recordGeneratedFile(root, manifest, ".gemini/settings.json", "managed-config");
  if (tools.includes("claude")) recordGeneratedFile(root, manifest, "CLAUDE.md", "managed-block");
  saveManifest(root, manifest);
  return { status: "READY", sync, adapters };
}

function staticToolCheck(root, tool, manifest) {
  const errors = [];
  const warnings = [];
  if (!manifest.adapters || !manifest.adapters[tool] || manifest.adapters[tool].status !== "READY") {
    errors.push(`${tool} adapter 尚未設定；請先執行 setup --tool ${tool}`);
  }
  const agentsPath = join(root, "AGENTS.md");
  if (!existsSync(agentsPath)) errors.push("AGENTS.md is missing");
  else {
    const expected = manifest.generated_files && manifest.generated_files["AGENTS.md"];
    if (!expected) errors.push("AGENTS.md is not recorded in generated-manifest.json");
    else if (sha256(readText(agentsPath)) !== expected.sha256) errors.push("AGENTS.md hash differs from generated manifest");
    if (manifest.policy && !readText(agentsPath).includes(manifest.policy.fingerprint)) errors.push("AGENTS.md does not contain the recorded fingerprint");
  }
  if (tool === "gemini") {
    const path = join(root, ".gemini", "settings.json");
    if (!existsSync(path)) errors.push(".gemini/settings.json is missing");
    else {
      const value = readJson(path);
      const fileName = value.context && value.context.fileName;
      const names = Array.isArray(fileName) ? fileName : [fileName];
      if (!names.includes("AGENTS.md")) errors.push("Gemini context.fileName does not include AGENTS.md");
      if (names.some((name) => name && name !== "AGENTS.md")) warnings.push("Gemini may load additional context files");
    }
  }
  if (tool === "claude") {
    const path = join(root, "CLAUDE.md");
    if (!existsSync(path) || !readText(path).includes("@AGENTS.md")) errors.push("CLAUDE.md does not import AGENTS.md");
  }
  if (tool === "opencode" && existsSync(join(root, "opencode.json"))) {
    const value = readJson(join(root, "opencode.json"));
    if (Array.isArray(value.instructions) && value.instructions.length) warnings.push("opencode.json loads additional instruction files");
  }
  return { ok: errors.length === 0, errors, warnings };
}

