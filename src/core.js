export function sha256(value) {
  return createHash("sha256").update(value).digest("hex");
}

function readText(path) {
  return readFileSync(path, "utf8");
}

function readJson(path) {
  try {
    return JSON.parse(readText(path));
  } catch (error) {
    throw new Error(`Invalid JSON in ${path}: ${error.message}`);
  }
}

function writeAtomic(path, content) {
  mkdirSync(dirname(path), { recursive: true });
  const temporary = `${path}.tmp-${process.pid}-${randomBytes(4).toString("hex")}`;
  writeFileSync(temporary, content, "utf8");
  renameSync(temporary, path);
}

function writeJson(path, value) {
  writeAtomic(path, `${JSON.stringify(value, null, 2)}\n`);
}

function timestamp() {
  return new Date().toISOString();
}

export function repositoryRoot(cwd = process.cwd()) {
  try {
    return execFileSync("git", ["rev-parse", "--show-toplevel"], {
      cwd,
      encoding: "utf8",
      stdio: ["ignore", "pipe", "ignore"],
    }).trim();
  } catch {
    throw new Error("Run this command inside a Git repository.");
  }
}

function assertAtRoot(cwd) {
  const root = repositoryRoot(cwd);
  if (realpathSync(root) !== realpathSync(cwd)) {
    throw new Error(`Run this command at the repository root: ${root}`);
  }
  return root;
}

function gitInfo(root) {
  const run = (args) => {
    try {
      return execFileSync("git", args, {
        cwd: root,
        encoding: "utf8",
        stdio: ["ignore", "pipe", "ignore"],
      }).trim();
    } catch {
      return "";
    }
  };
  return {
    branch: run(["branch", "--show-current"]),
    dirty: Boolean(run(["status", "--porcelain"])),
    head: run(["rev-parse", "HEAD"]),
  };
}

function walkFiles(root, limit = 5000) {
  const output = [];
  const visit = (directory) => {
    if (output.length >= limit) return;
    let entries = [];
    try {
      entries = readdirSync(directory, { withFileTypes: true });
    } catch {
      return;
    }
    entries.sort((a, b) => a.name.localeCompare(b.name));
    for (const entry of entries) {
      if (output.length >= limit) break;
      if (entry.name.startsWith(".") && entry.name !== ".github") continue;
      const absolute = join(directory, entry.name);
      if (entry.isDirectory()) {
        if (!IGNORED_DIRS.has(entry.name)) visit(absolute);
      } else if (entry.isFile()) {
        output.push(relative(root, absolute));
      }
    }
  };
  visit(root);
  return output;
}

function safePackageFacts(root) {
  const path = join(root, "package.json");
  if (!existsSync(path)) return null;
  const value = readJson(path);
  return {
    path: "package.json",
    name: typeof value.name === "string" ? value.name : null,
    package_manager: value.packageManager || null,
    scripts: value.scripts && typeof value.scripts === "object" ? value.scripts : {},
    engines: value.engines && typeof value.engines === "object" ? value.engines : {},
  };
}

export function collectInventory(root) {
  const files = walkFiles(root);
  const manifestPattern = /(^|\/)(package\.json|pyproject\.toml|requirements(?:[-.][^/]*)?\.txt|setup\.cfg|tox\.ini|noxfile\.py|Pipfile|poetry\.lock|uv\.lock|pytest\.ini|go\.mod|Cargo\.toml|pom\.xml|build\.gradle|build\.gradle\.kts|Gemfile|composer\.json|[^/]+\.sln|[^/]+\.(?:cs|fs)proj)$/;
  const manifests = files.filter((path) => manifestPattern.test(path));
  const ci = files.filter((path) =>
    path.startsWith(".github/workflows/") ||
    [".gitlab-ci.yml", "Jenkinsfile", "azure-pipelines.yml"].includes(path),
  );
  const tests = files.filter((path) =>
    /(^|\/)(test|tests|spec|specs)(\/|$)/i.test(path) ||
    /\.(test|spec)\.[cm]?[jt]sx?$/.test(path),
  );
  const topDirectories = Array.from(new Set(files.filter((path) => path.includes("/")).map((path) => path.split("/")[0]))).slice(0, 50);
  const existingInstructions = [
    "AGENTS.md", "CLAUDE.md", "GEMINI.md", "CONTRIBUTING.md", ".cursorrules",
  ].filter((path) => files.includes(path));
  const ecosystems = detectEcosystems(root, files);
  return {
    schema_version: "1",
    generated_at: timestamp(),
    repository: basename(root),
    git: gitInfo(root),
    manifests,
    package: safePackageFacts(root),
    ecosystems,
    ci_files: ci,
    test_files_sample: tests.slice(0, 30),
    top_directories: topDirectories,
    existing_instruction_files: existingInstructions,
    file_count_sampled: files.length,
    inventory_truncated: files.length >= 5000,
    note: "事實來自檔名與特定 manifest 欄位。命令只被識別，尚未執行。",
  };
}

function markdownCode(value) {
  return `\`${String(value).replace(/`/g, "\\`")}\``;
}

function inventoryFactsMarkdown(inventory) {
  const detectionWarnings = (inventory.ecosystems || []).flatMap((item) => item.detection_warnings || []);
  const detectedCommandCount = (inventory.ecosystems || []).reduce((count, item) => count + (item.commands || []).length, 0);
  const lines = [
    `- Repository：${markdownCode(inventory.repository)}`,
    `- Manifest：${inventory.manifests.length ? inventory.manifests.map(markdownCode).join("、") : "未偵測到"}`,
    `- Ecosystem：${inventory.ecosystems && inventory.ecosystems.length ? inventory.ecosystems.map((item) => markdownCode(`${item.id}:${item.root}`)).join("、") : "未確認"}`,
    `- 已確認的 ecosystem commands：${detectedCommandCount}`,
    `- Detection warnings：${detectionWarnings.length ? detectionWarnings.map(markdownCode).join("、") : "無"}`,
    `- 頂層目錄：${inventory.top_directories.length ? inventory.top_directories.map(markdownCode).join("、") : "未偵測到"}`,
    `- CI 檔案：${inventory.ci_files.length ? inventory.ci_files.map(markdownCode).join("、") : "未偵測到"}`,
    `- 抽樣的測試檔案數量：${inventory.test_files_sample.length}`,
    "- 命令狀態：只從設定中識別；初始化期間未執行任何 repository 命令。",
    `- Inventory scan：${inventory.inventory_truncated ? "已達 5000 個檔案上限，OWNER CONFIRMATION REQUIRED" : "未截斷"}。`,
  ];
  return lines.join("\n");
}

function ruleBlock(id, title, fields) {
  return [
    `### [${id}] ${title}`,
    "",
    `- Severity: ${fields.severity || "SHOULD"}`,
    `- Confidence: ${fields.confidence || "high"}`,
    `- Applies to: ${fields.applies}`,
    `- Requirement: ${fields.requirement}`,
    `- Evidence: ${fields.evidence}`,
    `- Verification: ${fields.verification}`,
    `- Recovery: ${fields.recovery}`,
  ].join("\n");
}

function deterministicRules(inventory) {
  const rules = [];
  let detectedCommands = (inventory.ecosystems || []).flatMap((item) =>
    (item.commands || []).map((detected) => ({ ...detected, ecosystem: item.id, ecosystem_root: item.root })),
  );
  if (!detectedCommands.length && inventory.package && inventory.package.scripts) {
    detectedCommands = ["test", "lint", "typecheck", "build"]
      .filter((kind) => typeof inventory.package.scripts[kind] === "string")
      .map((kind) => ({
        kind,
        argv: ["npm", "run", kind],
        cwd: ".",
        evidence: [`package.json scripts.${kind}`],
        ecosystem: "node",
        ecosystem_root: ".",
      }));
  }
  const definitions = [
    ["test", "REPO-TEST-001", "執行適用的 repository 測試命令"],
    ["lint", "REPO-QUALITY-001", "執行適用的 repository lint 命令"],
    ["typecheck", "REPO-TYPE-001", "執行適用的 repository typecheck 命令"],
    ["build", "REPO-BUILD-001", "執行適用的 repository build 命令"],
  ];
  for (const [kind, id, title] of definitions) {
    const commands = detectedCommands.filter((item) => item.kind === kind);
    if (!commands.length) continue;
    const commandSummary = commands.map((item) => `${item.argv.join(" ")}（${item.ecosystem_root}）`).join("、");
    const evidence = Array.from(new Set(commands.flatMap((item) => item.evidence || []))).map(markdownCode).join("、");
    rules.push(ruleBlock(id, title, {
      severity: kind === "test" ? "MUST" : "SHOULD",
      applies: "會影響對應 ecosystem 或 path 的變更",
      requirement: `宣告相關工作完成前，必須執行所有適用的已確認命令：${commandSummary}。`,
      evidence: `${evidence}；命令由 ecosystem detector 識別，初始化期間尚未執行。`,
      verification: "所有適用命令都必須以狀態碼 0 結束。OWNER CONFIRMATION REQUIRED。",
      recovery: "修復失敗，或說明原因並將未執行的命令標記為未驗證。",
    }));
  }
  if (inventory.ci_files.length) {
    rules.push(ruleBlock("REPO-CI-001", "保持已設定的 CI checks 通過", {
      severity: "MUST",
      applies: "所有會由 repository CI 評估的變更",
      requirement: "如果已知相關 CI check 失敗，不得宣告工作完成。",
      evidence: `在 ${inventory.ci_files.map(markdownCode).join("、")} 偵測到 CI 設定。`,
      verification: "相關 CI checks 通過，或已記錄核准的例外。OWNER CONFIRMATION REQUIRED。",
      recovery: "修復失敗的 check，或向 repository owner 申請例外。",
    }));
  }
  if (!rules.length) {
    rules.push(ruleBlock("REPO-REVIEW-001", "完成前確認 repository checks", {
      severity: "SHOULD",
      applies: "所有原始碼變更",
      requirement: "宣告工作完成前，應識別並執行相關的 repository checks。",
      evidence: "Inventory 期間未確認標準的 test、lint、typecheck 或 build 命令。",
      verification: "由 repository owner 確認正確的 checks。OWNER CONFIRMATION REQUIRED。",
      recovery: "記錄缺少的 checks，並在 owner review 後更新此 rule。",
    }));
  }
  return rules.join("\n\n");
}

export function generateProposal(inventory) {
  const template = readText(join(ROOT, "templates", "repo-policy-proposal.md"));
  return template
    .replace("{{FACTS}}", inventoryFactsMarkdown(inventory))
    .replace("{{RULES}}", deterministicRules(inventory));
}

